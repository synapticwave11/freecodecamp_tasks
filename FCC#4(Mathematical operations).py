#Numbers and Mathemathical operations

print("Numbers and Mathematical Operations")

#Integers
my_int_1= 56
my_int_2= -11

print(type(my_int_1))# <class 'int'>
print(type(my_int_2)) # <class 'int'>

#Addition with integers
sum_ints= my_int_1 + my_int_2
print('Integer Addition: ', sum_ints)

#Subtraction with integers
diff_ints= my_int_1 - my_int_2
print('Integer Subtraction: ', diff_ints)

#Multiplication with integers
product_ints= my_int_1 * my_int_2
print('Integer Multiplication: ', product_ints)

#Division with integers
div_ints= my_int_1 / my_int_2
print('Integer Division: ', div_ints)

#Floats
my_float_1= 3.14
my_float_2= -0.001
print(type(my_float_1)) # <class 'float'>
print(type(my_float_2)) # <class 'float'>

#Multiplication with floats
product_floats= my_float_1 * my_float_2
print('Float Multiplication: ', product_floats)

#Addition with floats
sum_floats= my_float_1 + my_float_2 
print('Float Addition: ', sum_floats) 

#Subtraction with floats
diff_floats= my_float_1 - my_float_2
print('Float Subtraction: ', diff_floats)

#Division with floats
div_floats= my_float_1 / my_float_2
print('Float Division: ', div_floats)

# Mixed Operations

my_int= 18
my_float=56.70

sum_int_and_float= my_int + my_float
print('Sum of Integer and Float: ', sum_int_and_float)

diff_int_and_float= my_int - my_float
print('Difference of Integer and Float: ', diff_int_and_float)

product_int_and_float= my_int * my_float
print('Product of Integer and Float: ', product_int_and_float)

div_int_and_float= my_int / my_float
print('Division of Integer and Float: ', div_int_and_float)


#Module operator

int_1= 10
int_2= 3

float_1= 11.1
float_2= 4.5

mod_ints= int_1 % int_2
mod_floats= float_1 % float_2

print('Module of Integers: ', mod_ints)
print('Module of Floats: ', mod_floats)
#floor division operator
floor_div_ints= int_1 // int_2
floor_div_floats= float_1 // float_2

print('Floor Division of Integers: ', floor_div_ints)
print('Floor Division of Floats: ', floor_div_floats)

#Exponentiation operator
exp_ints= int_1 ** int_2
exp_floats= float_1 ** float_2

print('Exponentiation of Integers: ', exp_ints)
print('Exponentiation of Floats: ', exp_floats)




